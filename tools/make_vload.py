#!/usr/bin/env python3
# Writes shaders/vload.vasm: the RSX load's vertex program (V0.9), for the RSX's eight vertex units.
# 256 four-float multiply-adds a vertex in four independent chains (each turns two lanes against each
# other, as the fragment shader's 1-register layout), folded into one value whose fractions go out as the
# colour - for the vertex check tile. cgcomp's assembler drops constants, so every number comes from the
# vertex's own attributes: position = seed, texcoord[0] = factors, texcoord[1] = fold weights,
# texcoord[2] = scales, color = where the vertex goes (a check pixel, or behind the eye: culled).
# cgcomp's assembler knows only the fixed register names R0-R31: a declared "TEMP r0" is assembled as no
# register at all (writes go nowhere, reads come from the input) - found in V0.9 through RPCS3's shader log.
#   python3 tools/make_vload.py > shaders/vload.vasm
MADS = 256
CHAINS = 4
SWZ = ["", ".yxwz", ".zwxy", ".wzyx"]
print("!!ARBvp1.0")
print("# generated by tools/make_vload.py - see there")
for c in range(CHAINS):
    print("MOV R%d, vertex.position%s;" % (c, SWZ[c]))
for i in range(MADS // CHAINS):
    for c in range(CHAINS):
        print("MAD R%d, R%d.yxwz, vertex.texcoord[0], R%d;" % (c, c, c))
print("ADD R0, R0, R1;")
print("ADD R2, R2, R3;")
print("ADD R0, R0, R2;")
print("DP4 R1.x, R0, vertex.texcoord[1];")
print("MUL R1, R1.x, vertex.texcoord[2];")
print("FRC R1, R1;")
print("MOV result.color, R1;")
print("MOV result.position, vertex.color;")
print("END")
